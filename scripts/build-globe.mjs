/**
 * Builds the data for the globe in Contact, from Natural Earth (public domain, naturalearthdata.com),
 * read from paths, not committed:
 *
 *   curl -sSL -o /tmp/ne_110m_land.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
 *   curl -sSL -o /tmp/ne-states.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson
 *   node scripts/build-globe.mjs /tmp/ne_110m_land.geojson /tmp/ne-states.geojson
 *
 * Two modules:
 * - src/components/places/globe-dots.ts: the land as dots (1:110m), a Fibonacci sphere of WORLD_POINTS
 *   points (point i at latitude asin(1 - 2(i + 0.5)/N), longitude i × the golden angle, wrapped to
 *   ±180°), stored as a bitmask (one bit per point, 1 = on land, base64), so the module stays a few KB;
 *   the component rebuilds the points from the same formulas.
 * - src/components/places/south-india-states.ts: the zoomed-in map (1:10m admin-1), the Indian states
 *   and the neighbours' provinces (Sri Lanka, Pakistan, Bangladesh, Nepal) that reach into the CLIP box,
 *   clipped to it and simplified in degrees
 *   (Douglas–Peucker, TOLERANCE), with every point where two states' borders meet or part kept, so a
 *   shared border simplifies the same way for both states and draws as one line. Rings are rounded to
 *   0.01° and stored as polyline strings (zigzag deltas in hundredths of a degree, 5-bit chunks, each
 *   chunk + 63 as a character, 0x20 = more chunks follow), the first point relative to (0, 0).
 */
import { readFileSync, writeFileSync } from "node:fs";

const [worldInput, statesInput] = process.argv.slice(2);
if (!worldInput || !statesInput) {
  console.error("usage: node scripts/build-globe.mjs <ne_110m_land.geojson> <ne_10m_admin_1_states_provinces.geojson>");
  process.exit(1);
}

const WORLD_POINTS = 20000;
/** The zoomed-in view's box (°E, °N): the view stays inside it once zoomed in. */
const BOX = { lon0: 70, lon1: 88, lat0: 4, lat1: 22 };
/**
 * The map is clipped to a larger box, so that mid-zoom, while the view still shows more than BOX and the
 * dots cross-fade into the map, no straight clip edge shows (the clip's edges are filled, never stroked).
 */
const CLIP = { lon0: 66, lon1: 92, lat0: 4, lat1: 26 };
/** Countries drawn as a lighter fill without borders, around India's states. */
const NEIGHBOURS = new Set(["LKA", "PAK", "BGD", "NPL"]);
const TOLERANCE = 0.016;
/** The neighbours only show faintly, mostly mid-zoom: coarser. */
const NEIGHBOUR_TOLERANCE = 0.04;
const GOLDEN = Math.PI * (3 - Math.sqrt(5));

/** Each feature's polygons as lists of rings of [lon, lat] (first the outline, then holes). */
const polygonsOf = (geometry) =>
  geometry.type === "Polygon" ? [geometry.coordinates] : geometry.type === "MultiPolygon" ? geometry.coordinates : [];

// ---- The world dots ----

function readLand(path) {
  const polygons = [];
  for (const feature of JSON.parse(readFileSync(path, "utf8")).features) {
    for (const rings of polygonsOf(feature.geometry)) {
      let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
      for (const [x, y] of rings[0]) {
        x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
      }
      polygons.push({ rings, box: [x0, y0, x1, y1] });
    }
  }
  return polygons;
}

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function onLand(polygons, lon, lat) {
  for (const { rings, box } of polygons) {
    if (lon < box[0] || lon > box[2] || lat < box[1] || lat > box[3]) continue;
    if (!inRing(rings[0], lon, lat)) continue;
    if (rings.slice(1).some((hole) => inRing(hole, lon, lat))) continue;
    return true;
  }
  return false;
}

function pack(bits) {
  const bytes = new Uint8Array(Math.ceil(bits.length / 8));
  bits.forEach((bit, i) => {
    if (bit) bytes[i >> 3] |= 1 << (i & 7);
  });
  return Buffer.from(bytes).toString("base64");
}

const worldLand = readLand(worldInput);
const world = [];
for (let i = 0; i < WORLD_POINTS; i++) {
  const lat = (Math.asin(1 - (2 * (i + 0.5)) / WORLD_POINTS) * 180) / Math.PI;
  let lon = ((i * GOLDEN * 180) / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  world.push(onLand(worldLand, lon, lat));
}

const dotsOut = `// Generated by scripts/build-globe.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// Regenerate: node scripts/build-globe.mjs /tmp/ne_110m_land.geojson /tmp/ne-states.geojson (downloads in the script).

/** Fibonacci sphere of \`count\` points; bit i of \`mask\` (base64, LSB first) is 1 when point i is on land. */
export const WORLD_DOTS = {
  count: ${WORLD_POINTS},
  mask: "${pack(world)}",
} as const;
`;
writeFileSync(new URL("../src/components/places/globe-dots.ts", import.meta.url), dotsOut);
console.log(`globe-dots.ts: ${world.filter(Boolean).length}/${WORLD_POINTS} world dots, ${dotsOut.length} bytes`);

// ---- The zoomed-in map ----

/** Sutherland–Hodgman against one edge of the box (the box is convex, so four passes clip to it). */
function clipEdge(ring, inside, cross) {
  const out = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[(i + ring.length - 1) % ring.length];
    const b = ring[i];
    if (inside(b)) {
      if (!inside(a)) out.push(cross(a, b));
      out.push(b);
    } else if (inside(a)) out.push(cross(a, b));
  }
  return out;
}
const atX = (x) => (a, b) => [x, a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0])];
const atY = (y) => (a, b) => [a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]), y];
function clip(ring) {
  let r = ring;
  r = clipEdge(r, (p) => p[0] >= CLIP.lon0, atX(CLIP.lon0));
  r = clipEdge(r, (p) => p[0] <= CLIP.lon1, atX(CLIP.lon1));
  r = clipEdge(r, (p) => p[1] >= CLIP.lat0, atY(CLIP.lat0));
  r = clipEdge(r, (p) => p[1] <= CLIP.lat1, atY(CLIP.lat1));
  return r;
}
const onBoxEdge = ([x, y]) => x === CLIP.lon0 || x === CLIP.lon1 || y === CLIP.lat0 || y === CLIP.lat1;

const area = (ring) => {
  let s = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) s += (ring[j][0] - ring[i][0]) * (ring[j][1] + ring[i][1]);
  return s / 2; // > 0 counter-clockwise
};

function segmentDistance(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len2 = dx * dx + dy * dy;
  const t = len2 ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2)) : 0;
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy);
}

/** Douglas–Peucker on an open run of points (keeps both ends). */
function simplifyRun(points, tolerance) {
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop();
    let worst = -1;
    let at = -1;
    for (let k = i + 1; k < j; k++) {
      const d = segmentDistance(points[k], points[i], points[j]);
      if (d > worst) {
        worst = d;
        at = k;
      }
    }
    if (worst > tolerance) {
      keep[at] = 1;
      stack.push([i, at], [at, j]);
    }
  }
  return points.filter((_, k) => keep[k]);
}

const statesData = JSON.parse(readFileSync(statesInput, "utf8"));
/** Clipped rings of each country, with the feature (state) each belongs to; GeoJSON's repeated closing point dropped. */
const rings = [];
statesData.features.forEach((feature, id) => {
  const country = feature.properties.adm0_a3;
  if (country !== "IND" && !NEIGHBOURS.has(country)) return;
  for (const polygon of polygonsOf(feature.geometry)) {
    polygon.forEach((source, k) => {
      const open = source.slice(0, -1);
      const clipped = clip(open);
      if (clipped.length < 3) return;
      // Outlines counter-clockwise, holes clockwise, so one non-zero fill draws them all.
      const ccw = area(clipped) > 0;
      if (ccw !== (k === 0)) clipped.reverse();
      rings.push({ country, id, points: clipped });
    });
  }
});

// Which states each point belongs to: a point whose set differs from a neighbour's is where a shared
// border begins or ends, and stays fixed, as do points on the box's edge.
const key = ([x, y]) => `${x.toFixed(7)},${y.toFixed(7)}`;
const owners = new Map();
for (const { id, points } of rings) {
  for (const p of points) {
    const k = key(p);
    if (!owners.has(k)) owners.set(k, new Set());
    owners.get(k).add(id);
  }
}
const ownerKey = (p) => [...owners.get(key(p))].sort((a, b) => a - b).join(",");

function simplifyRing(points, tolerance) {
  const n = points.length;
  const sets = points.map(ownerKey);
  const fixed = [];
  for (let i = 0; i < n; i++) {
    if (onBoxEdge(points[i]) || sets[i] !== sets[(i + n - 1) % n] || sets[i] !== sets[(i + 1) % n]) fixed.push(i);
  }
  if (fixed.length < 2) {
    // An island (or a ring with one neighbour all round): fix the first point and the one farthest from it.
    let far = 0;
    let best = -1;
    points.forEach((p, i) => {
      const d = Math.hypot(p[0] - points[0][0], p[1] - points[0][1]);
      if (d > best) {
        best = d;
        far = i;
      }
    });
    fixed.length = 0;
    fixed.push(0, far);
  }
  const out = [];
  for (let f = 0; f < fixed.length; f++) {
    const i = fixed[f];
    const j = fixed[(f + 1) % fixed.length];
    const run = j > i ? points.slice(i, j + 1) : [...points.slice(i), ...points.slice(0, j + 1)];
    out.push(...simplifyRun(run, tolerance).slice(0, -1));
  }
  return out;
}

const round = (v) => Math.round(v * 100);
function encode(points) {
  let s = "";
  let px = 0;
  let py = 0;
  const put = (v) => {
    let z = v < 0 ? ~(v << 1) : v << 1;
    while (z >= 0x20) {
      s += String.fromCharCode((0x20 | (z & 0x1f)) + 63);
      z >>= 5;
    }
    s += String.fromCharCode(z + 63);
  };
  for (const [x, y] of points) {
    put(x - px);
    put(y - py);
    px = x;
    py = y;
  }
  return s;
}

const encoded = { india: [], neighbours: [] };
let kept = 0;
for (const { country, points } of rings) {
  const india = country === "IND";
  const simple = simplifyRing(points, india ? TOLERANCE : NEIGHBOUR_TOLERANCE).map(([x, y]) => [round(x), round(y)]);
  const clean = simple.filter((p, i) => {
    const q = simple[(i + simple.length - 1) % simple.length];
    return p[0] !== q[0] || p[1] !== q[1];
  });
  // Too small to see at the zoomed-in scale (a few km², more for the neighbours' delta islands):
  // Lakshadweep's atolls, slivers of the clip.
  if (clean.length < 3 || Math.abs(area(clean)) < (india ? 4 : 40)) continue;
  kept += clean.length;
  encoded[india ? "india" : "neighbours"].push(encode(clean));
}

const statesOut = `// Generated by scripts/build-globe.mjs from Natural Earth 1:10m admin-1 states and provinces (public domain). Do not edit.
// Regenerate: node scripts/build-globe.mjs /tmp/ne_110m_land.geojson /tmp/ne-states.geojson (downloads in the script).

/**
 * The zoomed-in map: Indian states and the neighbours' provinces clipped to \`clip\` (°E, °N); the view stays
 * inside \`box\` once zoomed in. Each string is one
 * ring (outlines counter-clockwise, holes clockwise) as a polyline: zigzag deltas in hundredths of a degree,
 * lon then lat, in 5-bit chunks (char code - 63; 0x20 set = more chunks follow), from (0, 0).
 */
export const SOUTH_INDIA = {
  box: { lon0: ${BOX.lon0}, lon1: ${BOX.lon1}, lat0: ${BOX.lat0}, lat1: ${BOX.lat1} },
  clip: { lon0: ${CLIP.lon0}, lon1: ${CLIP.lon1}, lat0: ${CLIP.lat0}, lat1: ${CLIP.lat1} },
  india: ${JSON.stringify(encoded.india, null, 2).replace(/\n/g, "\n  ")},
  neighbours: ${JSON.stringify(encoded.neighbours, null, 2).replace(/\n/g, "\n  ")},
} as const;
`;
writeFileSync(new URL("../src/components/places/south-india-states.ts", import.meta.url), statesOut);
console.log(
  `south-india-states.ts: ${encoded.india.length} Indian rings, ${encoded.neighbours.length} neighbouring rings, ${kept} points, ${statesOut.length} bytes`,
);
